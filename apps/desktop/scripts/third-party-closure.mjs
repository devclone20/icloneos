// third-party-closure.mjs — every third-party npm package the desktop app ships, with its licence text, generated into
// THIRD_PARTY_NOTICES.md (K103, REL-2).
//
//   node scripts/third-party-closure.mjs            print what ships (name@version licence where)
//   node scripts/third-party-closure.mjs --write    regenerate the generated sections of THIRD_PARTY_NOTICES.md
//   node scripts/third-party-closure.mjs --check    re-render both sections and exit 1 unless the file matches them
//                                                    BYTE FOR BYTE (rows, licence column, every licence text)
//       [--repo <dir>]        another checkout (package-lock.json + THIRD_PARTY_NOTICES.md are read from it)
//       [--modules <dir>]     where the installed packages are (default: the repo)
//       [--acp-tree <dir>]    ignored since REL-6 (ruling 26: the ACP CLI is not shipped)
//
// Two generated sections, each between its own markers:
//
// 1. "Desktop app (app.asar)". The renderer (vite) and main/preload (esbuild) bundles inline their packages and drop
//    the packages' licence files, so the licence texts must live here. The set is the runtime closure, read from the
//    root package-lock.json with npm's own resolution, of the desktop workspace's declared `dependencies` and
//    `optionalDependencies` (also read from the lockfile), minus BUILD_ONLY, plus UNDECLARED and Electron. Packages
//    in OWN_FILES_ONLY ship only their own files, so their dependencies are not followed. Peer dependencies are not
//    followed: the ones a bundle really picks up are named in UNDECLARED, and `--check` scans the shipped sources for
//    any other bare import the closure does not cover. Workspace links (`@hermes/shared`) are first-party: followed,
//    never listed. The set is a superset of what the bundles contain (a declared dependency no file imports is still
//    listed); a bundle probe (vite + esbuild metafiles) proved every bundled package is in it.
//
// 2. The Virtuals ACP CLI is NOT shipped (REL-6, ruling 26): the app installs it at first use from the npm registry,
//    under each package's own licence, and lists what that install fetches in apps/desktop/acp-cli-lock/NOTICES.md
//    (scripts/acp-cli-notices.mjs). This file covers what the DMG ships, so `--write` removes any "ACP CLI" section
//    and `--check` refuses one; a staged ACP tree (stage-acp-cli.mjs, kept as a proof tool) is not read here.
//
// 3. "ACP native add-ons (Resources/acp-native)" (REL-6 r3, critic r2 M3; rulings 32 + 33). The macOS app ships its own
//    copies of the ACP CLI's native add-ons; their licence texts (package LICENSEs, and the Rust crates and Rust std
//    statically linked into the keyring binding) are committed and pinned in apps/desktop/acp-native-notices/ and the
//    section is rendered from them (acp-native-notices.mjs). `--check` also fails when an add-on of the pinned closure
//    has no notice or a committed text is missing, changed or unlisted.
//
// Licence texts come from the installed packages and a package whose installed version differs from the lockfile is
// refused (re-run `npm ci`). A package that ships no licence file gets the standard text of the licence it declares
// (MIT, ISC), marked as such; a package that declares no licence and ships none gets an explicit "no licence" entry.
// `--check` also fails on a shipped import the closure misses, and on any licence that is not plainly permissive
// (copyleft, custom, unknown, none) unless LICENCE_REVIEW names that exact name@version; the ones it names are printed
// as FLAG. Shipping those is the lead's call, not this script's: the list records what awaits a ruling.
