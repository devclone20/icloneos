/** A licence text as the notices render it: BOM and CR dropped, trailing blanks dropped (formatters strip them). */
export const normaliseText = raw =>
  raw
    .replace(/^\uFEFF/, '')
    .replace(/\r\n?/g, '\n')
    .replace(/[ \t]+$/gm, '')
    .trimEnd()

/** The OFL 1.1 body of a text (from its separator line), or null when it has none. */
export const oflBody = text => {
  const at = text.indexOf(OFL_SEPARATOR)

  return at < 0 ? null : text.slice(at).trimEnd()
}

