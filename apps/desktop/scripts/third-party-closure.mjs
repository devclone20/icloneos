const EXECUTABLE_MAGIC = ['cffaedfe', 'cefaedfe', 'feedfacf', 'feedface', 'cafebabe', '7f454c46']

function isExecutable(file) {
  if (file.endsWith('.node')) {
    return false
  }

  const head = Buffer.alloc(4)
  const fd = openSync(file, 'r')

  try {
    readSync(fd, head, 0, 4, 0)
  } finally {
    closeSync(fd)
  }

  return EXECUTABLE_MAGIC.includes(head.toString('hex')) || head.subarray(0, 2).toString('latin1') === 'MZ'
}

function ownFiles(dir, base = dir, out = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name)

    if (entry.isDirectory() && entry.name !== 'node_modules') {
      ownFiles(full, base, out)
    } else if (entry.isFile()) {
      out.push(relative(base, full).split('\\').join('/'))
    }
  }

  return out
}

/** The native executables of the staged tree's packages: [{ id, row, rel, path, entry }] (entry: NATIVE_BINARIES). */
export function nativeExecutables(treeDir, closure) {
  const found = []

  for (const row of closure.values()) {
    const id = `${row.name}@${row.version}`

    for (const key of row.paths) {
      const dir = join(treeDir, key)

      for (const rel of ownFiles(dir).filter(r => isExecutable(join(dir, r)))) {
        const entry = NATIVE_BINARIES[id]
        found.push({ id, rel, path: join(dir, rel), entry: entry && entry.files.test(rel) ? entry : null })
      }
    }
  }

  return found
}

/** Problems: an executable no entry covers, or a listed module the binary does not carry. */
export function nativeBinaryProblems(treeDir, closure, label = 'acp-cli') {
  const problems = []

  for (const bin of nativeExecutables(treeDir, closure)) {
    if (!bin.entry) {
      problems.push(`${label}: ${bin.id} ships the native executable ${bin.rel} with no notice entry (NATIVE_BINARIES)`)
      continue
    }

    const bytes = readFileSync(bin.path).toString('latin1')

    for (const m of bin.entry.modules) {
      if (!bytes.includes(m.marker)) {
        problems.push(
          `${label}: ${bin.id} ${bin.rel} does not carry ${m.module} ${m.version} (no "${m.marker}" in it): update NATIVE_BINARIES`
        )
      }
    }
  }

  return problems
}

/** The notice lines for the tree's native executables (rendered at the end of the ACP section). */
export function nativeBinaryNotice(treeDir, closure, dir = LICENCE_TEXT_DIR) {
  const lines = []

  // One block per package, not per file: the staged tree holds only this platform's signer, and the section must
  // render the same on every platform's build.
  const seen = new Map(
    nativeExecutables(treeDir, closure)
      .filter(b => b.entry)
      .map(b => [b.id, b.entry])
  )

  for (const [id, entry] of seen) {
    const { licence } = entry
    const raw = readFileSync(join(dir, licence.file))
    const sha = createHash('sha256').update(raw).digest('hex')

    if (sha !== licence.sha256) {
      throw new Error(`scripts/licence-texts/${licence.file} is not the upstream text (sha256 ${sha})`)
    }

    const body = raw
      .toString('utf8')
      .replace(/[ \t]+$/gm, '')
      .trimEnd()
    const fence = fenceFor(body)
    lines.push(`### Compiled into the native executables of \`${id}\``, '')
    lines.push(
      `${entry.what[0].toUpperCase()}${entry.what.slice(1)}; \`${entry.label}\` (each build ships its platform's`,
      'one). It embeds:',
      ''
    )
    lines.push(...entry.modules.map(m => `- ${m.module} ${m.version}: ${licence.id}`), '')
    lines.push(`${fence}text`, body, fence, '')
  }

  return lines
}

