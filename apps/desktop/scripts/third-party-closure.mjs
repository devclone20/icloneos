const LICENCE_TEXT_DIR = join(dirname(fileURLToPath(import.meta.url)), 'licence-texts')

/** The full texts `rows` require (ruling 19), each read from scripts/licence-texts and checked against its sha256. */
export function requiredCopyleftTexts(rows, dir = LICENCE_TEXT_DIR) {
  const out = []

  for (const rule of COPYLEFT_TEXTS) {
    const ids = rows.filter(r => rule.when.test(String(r.license ?? ''))).map(r => `${r.name}@${r.version}`)

    if (ids.length === 0) {
      continue
    }

    for (const text of rule.texts) {
      const raw = readFileSync(join(dir, text.file))
      const sha = createHash('sha256').update(raw).digest('hex')

      if (sha !== text.sha256) {
        throw new Error(
          `scripts/licence-texts/${text.file} is not the canonical text (sha256 ${sha}, want ${text.sha256})`
        )
      }

      out.push({
        ...text,
        ids,
        body: raw
          .toString('utf8')
          .replace(/[ \t]+$/gm, '')
          .trimEnd()
      })
    }
  }

  return out
}

