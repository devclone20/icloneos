/** A family's licence text, read from apps/desktop and checked against its pin and the OFL 1.1 body. */
export function fontLicenceText(family, desktopDir = DESKTOP_DIR) {
  const raw = readFileSync(join(desktopDir, family.licence.file))
  const sha = createHash('sha256').update(raw).digest('hex')

  if (sha !== family.licence.sha256) {
    throw new Error(
      `apps/desktop/${family.licence.file} is not the verbatim licence of ${family.font} (sha256 ${sha}, want ${family.licence.sha256})`
    )
  }

  const text = normaliseText(raw.toString('utf8'))
  const body = oflBody(text)

  if (!body || createHash('sha256').update(body).digest('hex') !== OFL_BODY_SHA256) {
    throw new Error(`apps/desktop/${family.licence.file}: its body is not the SIL Open Font License 1.1 text`)
  }

  return text
}

