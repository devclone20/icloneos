#!/usr/bin/env node
// acp-cli-notices.mjs — REL-6 (ruling 26): acp-cli-lock/NOTICES.md, generated from the committed lockfile.
//
// The ACP CLI is NOT in the app bundle, so its packages are not in THIRD_PARTY_NOTICES.md (which covers what the
// DMG ships). The app installs the CLI at first use from the npm registry, under each package's own licence; this
// file is the record of what that install fetches, and the app shows the installed tree's own licence texts after
// the install (userData/acp-cli/<lock-sha256>/NOTICES.md, written by electron/iclone-acp-tools/).
//
//   node scripts/acp-cli-notices.mjs           # write acp-cli-lock/NOTICES.md
//   node scripts/acp-cli-notices.mjs --check   # exit 1 when it is not what the lockfile says
//
// Licences come from the lockfile's own `license` field (each package's package.json). A row that declares none is
// listed as such: it is fetched from npm under its publisher's terms and never redistributed by iclone os.

import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import { isMain } from './utils.mjs'

const DESKTOP = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
export const LOCK_DIR = path.join(DESKTOP, 'acp-cli-lock')
export const NOTICES_FILE = path.join(LOCK_DIR, 'NOTICES.md')

const { ACP_CLI_NAME, parsePin, runtimeClosure } = await import('../src/iclone-shared/acp-pin.ts')

const platformsOf = row =>
  row.os || row.cpu ? `${(row.os ?? ['any']).join('/')} ${(row.cpu ?? ['any']).join('/')}`.trim() : 'all'

/** The NOTICES.md text for one pin (package.json + package-lock.json text). */
export function renderAcpNotices(packageJsonText, lockText) {
  const pin = parsePin(packageJsonText, lockText)
  const rows = runtimeClosure(pin, null)
  const lockSha = createHash('sha256').update(lockText).digest('hex')
  const width = (pick, title) => Math.max(title.length, ...rows.map(row => pick(row).length))
  const cell = row => ({
    pkg: `\`${row.key.replace(/^node_modules\//, '')}\``,
    version: row.version,
    licence: row.license ?? 'none declared',
    platforms: platformsOf(row)
  })
  const cells = rows.map(cell)
  const w = {
    pkg: width(row => cell(row).pkg, 'Package (install path under node_modules/)'),
    version: width(row => row.version, 'Version'),
    licence: width(row => cell(row).licence, 'Licence (as declared)'),
    platforms: width(row => platformsOf(row), 'Installed on')
  }
  const line = (a, b, c, d) =>
    `| ${a.padEnd(w.pkg)} | ${b.padEnd(w.version)} | ${c.padEnd(w.licence)} | ${d.padEnd(w.platforms)} |`
  const unlicensed = rows.filter(row => !row.license)
  const seeLicence = rows.filter(row => /^SEE LICEN[CS]E IN /i.test(row.license ?? ''))

  return [
    '<!-- GENERATED by apps/desktop/scripts/acp-cli-notices.mjs from package-lock.json; edit the script, not this -->',
    '',
    '# ACP CLI — what the first-use install fetches (not shipped in the app)',
    '',
    `iclone os does not ship the Virtuals ACP CLI (\`${ACP_CLI_NAME}\` ${pin.cliVersion}). When the owner chooses`,
    '"Install (downloads from npm)", the app fetches each package below from https://registry.npmjs.org/, checks it',
    'against the sha512 in `package-lock.json`, and installs it into its own folder',
    '(`userData/acp-cli/<sha256 of package-lock.json>/`). Each package comes under its own licence, as its publisher',
    "releases it on npm; the app shows the installed packages' own licence texts after the install. Nothing below is",
    'redistributed by iclone os.',
    '',
    `Pin: \`package-lock.json\` sha256 \`${lockSha}\`. ${rows.length} packages in the CLI's runtime closure across`,
    "platforms (each install takes only its own platform's rows; build tooling and type stubs are never fetched).",
    '',
    unlicensed.length > 0
      ? `Declaring no licence (${unlicensed.length}): ${unlicensed.map(row => `\`${row.name}@${row.version}\``).join(', ')}. ` +
        "These are fetched from npm under their publishers' terms."
      : 'Every package declares a licence.',
    '',
    seeLicence.length > 0
      ? `Declaring \`SEE LICENSE IN <file>\` (${seeLicence.length}): ${seeLicence.map(row => `\`${row.name}@${row.version}\``).join(', ')}. ` +
        'Each tarball carries that file; the install keeps every licence and notice file, and the in-app notices show ' +
        'its text.'
      : 'No package refers to a licence file instead of naming its licence.',
    '',
    'Native code the install fetches, all of it inside the npm tarballs above (pinned by their sha512): the Go signer',
    `\`bin/acp-cli-signer-<os>\` published inside \`${ACP_CLI_NAME}\` itself (only this platform's is installed;`,
    'built by its publisher, not from iclone os source), and the N-API addons `@napi-rs/keyring-<platform>`,',
    '`bufferutil` and `utf-8-validate` (their `prebuilds/<platform>-<arch>`). No install script runs.',
    '',
    line('Package (install path under node_modules/)', 'Version', 'Licence (as declared)', 'Installed on'),
    line('-'.repeat(w.pkg), '-'.repeat(w.version), '-'.repeat(w.licence), '-'.repeat(w.platforms)),
    ...cells.map(c => line(c.pkg, c.version, c.licence, c.platforms)),
    ''
  ].join('\n')
}

export function readLock(dir = LOCK_DIR) {
  return {
    packageJson: readFileSync(path.join(dir, 'package.json'), 'utf8'),
    lock: readFileSync(path.join(dir, 'package-lock.json'), 'utf8')
  }
}

if (isMain(import.meta.url)) {
  const { packageJson, lock } = readLock()
  const text = renderAcpNotices(packageJson, lock)

  if (process.argv.includes('--check')) {
    let current = ''

    try {
      current = readFileSync(NOTICES_FILE, 'utf8')
    } catch {
      // missing: fails below
    }

    if (current !== text) {
      console.error(
        '[acp-cli-notices] acp-cli-lock/NOTICES.md is not what the lockfile says: run node scripts/acp-cli-notices.mjs'
      )
      process.exit(1)
    }

    console.log('[acp-cli-notices] ok')
  } else {
    writeFileSync(NOTICES_FILE, text)
    console.log(`[acp-cli-notices] wrote ${path.relative(DESKTOP, NOTICES_FILE)}`)
  }
}
