const SURFACE =
  /role=["']alert["']|role=\{[^}]*'alert'|aria-live=|new Notification\(|\.showMessageBox(?:Sync)?\(|\.showErrorBox\(/

function* sources(dir: string): Generator<string> {
  for (const name of readdirSync(dir)) {
    const full = path.join(dir, name)

    if (statSync(full).isDirectory()) {
      if (name !== 'node_modules' && name !== '__tests__') {
        yield* sources(full)
      }
    } else if (/\.(ts|tsx)$/.test(name) && !/\.(test|spec)\.(ts|tsx)$/.test(name) && !name.endsWith('.d.ts')) {
      yield full
    }
  }
}

const read = (relative: string) => readFileSync(path.join(ROOT, relative), 'utf8')

describe('N1 · no notification surface outside the five types', () => {
  it('the scan equals the registry', () => {
    const found = ['src', 'electron']
      .flatMap(dir => [...sources(path.join(ROOT, dir))])
      .filter(file => SURFACE.test(readFileSync(file, 'utf8')))
      .map(file => path.relative(ROOT, file).split(path.sep).join('/'))
      .sort()

    const unlisted = found.filter(file => !(file in INVENTORY))
    const stale = Object.keys(INVENTORY).filter(file => !found.includes(file))

    expect({ stale, unlisted }).toEqual({ stale: [], unlisted: [] })
  })

  it('the status banner no longer draws its own surface (it renders through IcStatusBanner)', () => {
    const banner = read('src/components/agent-stopped-banner.tsx')

    expect(banner).toContain('IcStatusBanner')
    expect(banner).not.toMatch(/aria-live=|role=|\btruncate\b/)
  })

  it('the old split stack, its "+N more" expander and the 4-cap are gone', () => {
    const view = read('src/components/notifications.tsx')
    const store = read('src/store/notifications.ts')

    expect(view).not.toMatch(/TopCenterStack|BottomRightStack|clearAll/)
    expect(store).not.toMatch(/\.slice\(0, 4\)/)
  })
})

