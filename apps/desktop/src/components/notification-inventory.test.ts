describe('N5 · no caller shortens a toast below the reading time', () => {
  it('no notify() passes a literal durationMs between 1 ms and 9.999 s', () => {
    const offenders: string[] = []

    for (const file of sources(path.join(ROOT, 'src'))) {
      const text = readFileSync(file, 'utf8')

      if (!/\bnotify\(/.test(text)) {
        continue
      }

      for (const match of text.matchAll(/notify\(\{[^}]*?durationMs:\s*([\d_]+)/g)) {
        const ms = Number(match[1].replace(/_/g, ''))

        if (ms > 0 && ms < 10_000) {
          offenders.push(`${path.relative(ROOT, file)}: ${ms}`)
        }
      }
    }

    expect(offenders).toEqual([])
  })
})

