const BY_LOCALE: Record<Locale, UpdatesCopy> = { ar, en, ja, 'pt-PT': ptPt, zh, 'zh-hant': zhHant }

export function updatesCopy(locale: Locale): UpdatesCopy {
  return BY_LOCALE[locale] ?? en
}

export function useUpdatesCopy(): UpdatesCopy {
  return updatesCopy(useI18n().locale)
}
