/** sw.js: caches only hashed /assets/* files (cache-first) and the offline page; never a gateway answer. */
export function serviceWorkerSource(cacheName: string): string {
  return `// icloneOS Web service worker (generated by vite.web.config.ts)
const CACHE = ${JSON.stringify(cacheName)}
const OFFLINE = '/offline.html'
${swRoute.toString()}
self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE).then(cache => cache.add(OFFLINE)).then(() => self.skipWaiting()))
})
self.addEventListener('activate', event => {
  event.waitUntil(
    caches.keys()
      .then(keys => Promise.all(keys.filter(key => key !== CACHE).map(key => caches.delete(key))))
      .then(() => self.clients.claim())
  )
})
self.addEventListener('fetch', event => {
  const url = new URL(event.request.url)
  if (url.origin !== self.location.origin) return
  const route = swRoute(url.pathname, event.request.method, event.request.mode)
  if (route === 'navigate') {
    event.respondWith(fetch(event.request).catch(() => caches.match(OFFLINE)))
  } else if (route === 'asset') {
    event.respondWith(
      caches.match(event.request).then(hit => hit || fetch(event.request).then(response => {
        if (response.ok) {
          const copy = response.clone()
          caches.open(CACHE).then(cache => cache.put(event.request, copy))
        }
        return response
      }))
    )
  }
})
`
}
